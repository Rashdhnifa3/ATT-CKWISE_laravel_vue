#!/usr/bin/env node
// Copies the Angular reference Playwright specs (nav-app/e2e) and their synthetic fixtures into
// tests/e2e/reference so the SAME scenarios run against the Vue build. Only module paths and the
// D3FEND asset path are rewritten. `--check` fails if the committed copies drift from the reference.
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const navE2E = resolve(root, '../../nav-app/e2e');
const navMock = resolve(root, '../../nav-app/src/tests/utils/mock-data.ts');
const outDir = resolve(root, 'tests/e2e/reference');
const sharedMock = resolve(root, '../shared/fixtures/mock-data.ts');
const check = process.argv.includes('--check');

const rewrites = [
    [/'\.\.\/src\/tests\/utils\/mock-data'/g, "'../../../../shared/fixtures/mock-data'"],
    [/'\.\.\/src\/assets\/config\.json'/g, "'../../../public/assets/config.json'"],
    [/'\.\.\/src\/app\/planning\/([a-z0-9-]+)'/g, "'../../../src/planning/$1'"],
    [/'src\/assets\/d3fend\/attack-d3fend\.json'/g, "'public/assets/d3fend/attack-d3fend.json'"],
];
const header = (src) => `// GENERATED by scripts/sync-reference-specs.mjs from nav-app/e2e/${src}. Do not edit; only import paths are rewritten.\n`;
const transform = (text) => rewrites.reduce((t, [re, to]) => t.replace(re, to), text);

const files = readdirSync(navE2E).filter((f) => f.endsWith('.spec.ts') || f === 'mock-attack-data.ts');
const outputs = files.map((f) => [resolve(outDir, f), header(f) + transform(readFileSync(resolve(navE2E, f), 'utf8'))]);
outputs.push([sharedMock, '// GENERATED copy of nav-app/src/tests/utils/mock-data.ts (MITRE ATT&CK Navigator synthetic test data, Apache-2.0).\n' + readFileSync(navMock, 'utf8')]);

let drift = 0;
for (const [path, content] of outputs) {
    if (check) {
        if (!existsSync(path) || readFileSync(path, 'utf8') !== content) {
            console.error('drift: ' + path);
            drift++;
        }
    } else {
        mkdirSync(dirname(path), { recursive: true });
        writeFileSync(path, content);
    }
}
if (check && drift) process.exit(1);
console.log(`${check ? 'checked' : 'wrote'} ${outputs.length} files`);
